import { expect, test } from '@playwright/test';
import { navigate } from './navigation';

test('respuesta confirmada → nota → edición y aprobación → reapertura, sin duplicar ni alterar el mensaje', async ({ page, context }) => {
  test.setTimeout(120000);
  let generated = 0;
  for (const prefix of ['projects', 'artifacts', 'conversations']) await context.route(`**/api/${prefix}**`, async route => {
    if (route.request().url().endsWith('/messages') || route.request().url().endsWith('/artifacts/generate')) generated++;
    const response = await route.fetch({ url: route.request().url().replace('127.0.0.1:5174', '127.0.0.1:3102') });
    await route.fulfill({ response });
  });
  await page.goto('/');
  await navigate(page, /^Biblioteca/);
  await page.getByRole('button', { name: 'Nuevo proyecto', exact: true }).click();
  await page.getByLabel('Nombre del proyecto').fill('Resultados en contexto E2E');
  await page.getByRole('button', { name: 'Crear proyecto', exact: true }).click();
  await navigate(page, /^Consola táctica/);
  await page.getByRole('button', { name: 'Nueva conversación', exact: true }).click();
  await page.getByRole('textbox', { name: 'Mensaje para A.R.E.S.' }).fill('Documenta la regla de pedidos');
  await page.getByRole('button', { name: 'Enviar mensaje', exact: true }).click();
  const original = await page.locator('.message.model .markdown').innerText();
  await page.getByRole('button', { name: 'Abrir resultado', exact: true }).click();
  const panel = page.getByRole('complementary', { name: 'Resultado en contexto' });
  const save = page.waitForResponse(response => response.url().endsWith('/notes') && response.status() === 200);
  await panel.getByRole('button', { name: 'Guardar nota en Biblioteca' }).click();
  const first = (await (await save).json()).artifact;
  await expect(panel.getByRole('region', { name: 'Gestión del documento' })).toBeVisible();
  await panel.getByRole('button', { name: 'Editar documento', exact: true }).click();
  await panel.getByLabel('Título del documento').fill('Edición que se descarta');
  await panel.getByRole('button', { name: 'Cancelar edición', exact: true }).click();
  await panel.getByRole('button', { name: 'Editar documento', exact: true }).click();
  await expect(panel.getByLabel('Título del documento')).toHaveValue(first.title);
  await panel.getByLabel('Título del documento').fill('Regla revisada de pedidos');
  await panel.getByLabel('Contenido del documento').fill('# Regla revisada\n\nNo confirmar un pedido vacío.');
  await panel.getByRole('button', { name: 'Cerrar resultado' }).click();
  await page.getByRole('button', { name: 'Abrir resultado', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('Guarda o cancela');
  await expect(panel.getByLabel('Título del documento')).toHaveValue('Regla revisada de pedidos');
  await panel.getByRole('button', { name: 'Guardar revisión', exact: true }).click();
  await expect(panel).toContainText('Revisión 1');
  await panel.getByRole('button', { name: 'Aprobar revisión', exact: true }).click();
  await expect(panel).toContainText('APROBADO POR EL USUARIO');
  await expect(page.locator('.message.model .markdown')).toHaveText(original);
  expect(generated).toBe(1);
  await panel.getByRole('button', { name: 'Cerrar resultado' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Abrir resultado', exact: true }).click();
  const repeat = page.waitForResponse(response => response.url().endsWith('/notes') && response.status() === 200);
  await panel.getByRole('button', { name: 'Guardar nota en Biblioteca' }).click();
  const reopened = (await (await repeat).json()).artifact;
  expect(reopened.id).toBe(first.id); expect(reopened.title).toBe('Regla revisada de pedidos');
  await expect(panel).toContainText('Revisión aprobada');
  await panel.getByRole('button', { name: 'Usar en mensaje', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Mensaje para A.R.E.S.' })).toHaveValue(/No confirmar un pedido vacío/);
  await panel.getByRole('button', { name: 'Ver en Biblioteca', exact: true }).click();
  await expect(page.locator('.artifact-card')).toHaveCount(1);
  await page.getByRole('button', { name: 'Ver junto al chat', exact: true }).click();
  await expect(panel).toContainText('Regla revisada de pedidos');
  expect(generated).toBe(1);
});

test.afterEach(async ({ context }) => context.unrouteAll({ behavior: 'ignoreErrors' }));
