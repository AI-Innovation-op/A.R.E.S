import { expect, test } from '@playwright/test';
import { navigate } from './navigation';

test('resultado junto al chat: diagrama, código, diff, origen y borrador sin reconsultar al modelo', async ({ page }) => {
  let calls = 0;
  const content = '# Diseño de pedidos\n\nPropuesta pendiente de comprobar.\n\n```mermaid\nflowchart LR\nPedido --> Inventario\n```\n\n```ts\nexport const total = 2;\n```';
  await page.route('**/api/chat', route => { calls++; return route.fulfill({ json: { content, sources: [], provider: 'openrouter', model: 'context-fixture' } }); });
  await page.goto('/');
  const input = page.getByRole('textbox', { name: 'Mensaje para A.R.E.S.' });
  await input.fill('Diseña pedidos con un diagrama y un ejemplo de código.');
  await page.getByRole('button', { name: 'Enviar mensaje', exact: true }).click();
  const trigger = page.getByRole('button', { name: 'Abrir resultado', exact: true });
  await trigger.click();
  const panel = page.getByRole('complementary', { name: 'Resultado en contexto' });
  await expect(panel).toBeVisible();
  await expect(panel.getByRole('button', { name: 'Guardar nota en Biblioteca' })).toBeDisabled();
  await panel.getByRole('tab', { name: 'Diagramas', exact: true }).click();
  await expect(panel.getByRole('img', { name: 'Diagrama Mermaid' })).toBeVisible({ timeout: 30000 });
  await panel.getByRole('tab', { name: 'Código', exact: true }).click();
  await expect(panel.locator('.result-code')).toContainText('export const total = 2;');
  await panel.getByRole('tab', { name: 'Comparar', exact: true }).click();
  await panel.getByLabel('Original para comparar').fill('export const total = 1;');
  const comparison = panel.getByRole('region', { name: 'Comparación Antes y Después' });
  await expect(comparison).toHaveAttribute('data-ready', 'true', { timeout: 30000 });
  await expect(comparison.locator('.original .view-lines')).toContainText(/total\s*=\s*1/);
  await expect(comparison.locator('.modified .view-lines')).toContainText(/total\s*=\s*2/);
  await panel.getByRole('tab', { name: 'Origen', exact: true }).click();
  await expect(panel).toContainText('Diseña pedidos con un diagrama');
  await expect(panel).toContainText('context-fixture');
  await panel.getByRole('button', { name: 'Usar en mensaje', exact: true }).click();
  await expect(input).toHaveValue(/export const total = 2/);
  expect(calls).toBe(1);
  const box = await input.boundingBox(); expect(box!.y + box!.height).toBeLessThan(1100);
  await page.screenshot({ path: 'test-results/result-workspace-desktop.png', fullPage: true });
  await panel.getByRole('button', { name: 'Cerrar resultado' }).click();
  await expect(trigger).toBeFocused();
  await page.setViewportSize({ width: 390, height: 844 });
  await trigger.click();
  const mobile = page.getByRole('dialog', { name: 'Resultado en contexto' });
  await expect(mobile).toHaveAttribute('aria-modal', 'true');
  await expect(page.locator('.chat-panel')).toHaveAttribute('inert', '');
  await page.screenshot({ path: 'test-results/result-workspace-mobile.png', fullPage: true });
  await page.keyboard.press('Escape');
  await expect(mobile).toBeHidden();
  await expect(trigger).toBeFocused();
  await expect(input).toHaveValue(/export const total = 2/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('un borrador de un módulo puede abrirse junto a la conversación existente', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('textbox', { name: 'Mensaje para A.R.E.S.' }).fill('Pregunta pendiente que debe conservarse');
  await navigate(page, /Escudo Documental/);
  await page.getByLabel('Contexto, requisitos o código del proyecto').fill('Proyecto sintético de pedidos.');
  await page.getByRole('button', { name: 'Forjar documento', exact: true }).click();
  await page.getByRole('button', { name: 'Ver junto al chat', exact: true }).click();
  await expect(page.getByRole('complementary', { name: 'Resultado en contexto' })).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Mensaje para A.R.E.S.' })).toHaveValue('Pregunta pendiente que debe conservarse');
});
